// compilerFuzzManifest obtains Go's recognized target table without executing
// TestMain, which can suppress ordinary list output while returning success.
func compilerFuzzManifest(ctx context.Context, root string, patterns, environment []string) ([]fuzzTarget, error) {
	run := goCommand(root, append([]string{goListVerb, "-compiled", "-test", jsonFlag}, patterns...)...)
	run.fuzzLifecycle = true
	run.env = environment
	output, err := run.output(ctx)
	if err != nil {
		return nil, fmt.Errorf("fuzz compiler manifest: %w", err)
	}
	return parseCompilerFuzzManifest(ctx, strings.NewReader(output))
}

func parseCompilerFuzzManifest(ctx context.Context, reader io.Reader) ([]fuzzTarget, error) {
	packages := map[string]discoveredPackage{}
	decoder := json.NewDecoder(reader)
	for {
		if err := ctx.Err(); err != nil {
			return nil, fmt.Errorf("fuzz compiler manifest canceled: %w", err)
		}
		var pkg discoveredPackage
		if err := decoder.Decode(&pkg); errors.Is(err, io.EOF) {
			break
		} else if err != nil {
			return nil, fmt.Errorf("%w: invalid fuzz compiler metadata: %w", errGate, err)
		}
		if pkg.ImportPath == "" || pkg.Error != nil || len(pkg.DepsErrors) != 0 {
			return nil, fmt.Errorf("%w: incomplete fuzz compiler package %q", errGate, pkg.ImportPath)
		}
		if _, exists := packages[pkg.ImportPath]; exists {
			return nil, fmt.Errorf("%w: duplicate fuzz compiler package %s", errGate, pkg.ImportPath)
		}
		packages[pkg.ImportPath] = pkg
	}
	if len(packages) == 0 {
		return nil, fmt.Errorf("%w: empty fuzz compiler metadata", errGate)
	}

	var targets []fuzzTarget
	for _, pkg := range packages {
		if err := ctx.Err(); err != nil {
			return nil, fmt.Errorf("fuzz compiler manifest canceled: %w", err)
		}
		if pkg.ForTest != "" || len(pkg.TestGoFiles)+len(pkg.XTestGoFiles) == 0 {
			continue
		}
		main, exists := packages[pkg.ImportPath+foreignTestSuffix]
		if !exists || main.Name != foreignTestMain || main.ForTest != "" || len(main.GoFiles) != 1 || !filepath.IsAbs(main.GoFiles[0]) {
			return nil, fmt.Errorf("%w: missing generated fuzz manifest for %s", errGate, pkg.ImportPath)
		}
		data, err := readCompilerFuzzMain(main.GoFiles[0])
		if err != nil {
			return nil, fmt.Errorf("read generated fuzz manifest for %s: %w", pkg.ImportPath, err)
		}
		if !strings.HasPrefix(strings.TrimSpace(string(data)), "// Code generated by 'go test'. DO NOT EDIT.") {
			return nil, fmt.Errorf("%w: unexpected generated fuzz manifest for %s", errGate, pkg.ImportPath)
		}
		listed, err := compilerFuzzTargets(pkg.ImportPath, data)
		if err != nil {
			return nil, err
		}
		targets = append(targets, listed...)
	}
	if err := ctx.Err(); err != nil {
		return nil, fmt.Errorf("fuzz compiler manifest canceled: %w", err)
	}
	return targets, nil
}

// The shared artifact reader proves regular-file identity before reading bytes.
func readCompilerFuzzMain(path string) ([]byte, error) {
	reader, err := regularArtifactReader(filepath.Dir(path))(filepath.Base(path))
	if err != nil {
		return nil, err
	}
	data, readErr := io.ReadAll(reader)
	return data, errors.Join(readErr, reader.Close())
}

// compilerFuzzTargets reads only the generated table, not similarly named
// declarations, methods, fixture strings or the source's own Fuzz naming rules.
func compilerFuzzTargets(pkg string, data []byte) ([]fuzzTarget, error) {
	file, err := parser.ParseFile(token.NewFileSet(), "generated-testmain.go", data, 0)
	if err != nil {
		return nil, fmt.Errorf("%w: invalid generated fuzz manifest for %s: %w", errGate, pkg, err)
	}
	if file.Name.Name != foreignTestMain {
		return nil, fmt.Errorf("%w: generated fuzz manifest is not main for %s", errGate, pkg)
	}
	testingAlias := ""
	for _, imported := range file.Imports {
		name, unquoteErr := strconv.Unquote(imported.Path.Value)
		if unquoteErr != nil {
			return nil, fmt.Errorf("%w: invalid generated fuzz import: %w", errGate, unquoteErr)
		}
		if name == "testing" {
			testingAlias = "testing"
			if imported.Name != nil {
				testingAlias = imported.Name.Name
			}
		}
	}

	var table *ast.CompositeLit
	for _, declaration := range file.Decls {
		group, ok := declaration.(*ast.GenDecl)
		if !ok || group.Tok != token.VAR {
			continue
		}
		for _, spec := range group.Specs {
			value, ok := spec.(*ast.ValueSpec)
			if !ok || len(value.Names) != 1 || value.Names[0].Name != "fuzzTargets" {
				continue
			}
			if table != nil || len(value.Values) != 1 {
				return nil, fmt.Errorf("%w: ambiguous generated fuzz table for %s", errGate, pkg)
			}
			table, ok = value.Values[0].(*ast.CompositeLit)
			if !ok {
				return nil, fmt.Errorf("%w: invalid generated fuzz table for %s", errGate, pkg)
			}
		}
	}
	if table == nil || testingAlias == "" {
		return nil, fmt.Errorf("%w: generated fuzz table missing for %s", errGate, pkg)
	}
	array, ok := table.Type.(*ast.ArrayType)
	if !ok || array.Len != nil {
		return nil, fmt.Errorf("%w: invalid generated fuzz table type for %s", errGate, pkg)
	}
	element, ok := array.Elt.(*ast.SelectorExpr)
	if !ok || element.Sel.Name != "InternalFuzzTarget" {
		return nil, fmt.Errorf("%w: invalid generated fuzz target type for %s", errGate, pkg)
	}
	owner, ok := element.X.(*ast.Ident)
	if !ok || owner.Name != testingAlias {
		return nil, fmt.Errorf("%w: generated fuzz table lacks testing attribution for %s", errGate, pkg)
	}

	var targets []fuzzTarget
	seen := map[string]bool{}
	for _, entry := range table.Elts {
		row, ok := entry.(*ast.CompositeLit)
		if !ok || len(row.Elts) != 2 {
			return nil, fmt.Errorf("%w: invalid generated fuzz target for %s", errGate, pkg)
		}
		label, ok := row.Elts[0].(*ast.BasicLit)
		if !ok || label.Kind != token.STRING {
			return nil, fmt.Errorf("%w: generated fuzz target lacks name for %s", errGate, pkg)
		}
		name, unquoteErr := strconv.Unquote(label.Value)
		if unquoteErr != nil || name == "" || seen[name] {
			return nil, fmt.Errorf("%w: invalid or duplicate generated fuzz name for %s", errGate, pkg)
		}
		function, ok := row.Elts[1].(*ast.SelectorExpr)
		if !ok || function.Sel.Name != name {
			return nil, fmt.Errorf("%w: generated fuzz name/function mismatch for %s", errGate, pkg)
		}
		seen[name] = true
		targets = append(targets, fuzzTarget{pkg: pkg, name: name})
	}
	return targets, nil
}

func compareFuzzManifest(listed, compiled []fuzzTarget) error {
	observed := map[fuzzTarget]bool{}
	for _, target := range listed {
		observed[target] = true
	}
	for _, target := range compiled {
		if !observed[target] {
			return fmt.Errorf("%w: fuzz discovery omitted compiler target %s %s", errGate, target.pkg, target.name)
		}
		delete(observed, target)
	}
	for target := range observed {
		return fmt.Errorf("%w: fuzz discovery listed noncompiler target %s %s", errGate, target.pkg, target.name)
	}
	return nil
}
