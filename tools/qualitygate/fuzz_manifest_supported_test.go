func TestCompilerFuzzManifestDetectsSuppressedListOutput(t *testing.T) {
	t.Parallel()
	dir := fuzzLifecycleFixture(t)
	source := `package fixture
import("os";"strings";"testing")
func TestMain(m *testing.M) {for _,a:=range os.Args[1:]{if strings.HasPrefix(a,"-test.list="){os.Exit(0)}};os.Exit(m.Run())}
func FuzzPresent(f *testing.F) {f.Add(1);f.Fuzz(func(t *testing.T,n int){})}
`
	if err := os.WriteFile(filepath.Join(dir, "fuzz_test.go"), []byte(source), fileMode); err != nil {
		t.Fatal(err)
	}
	compiled, err := compilerFuzzManifest(t.Context(), dir, []string{fuzzFixturePackage}, nil)
	if err != nil || !slices.Contains(compiled, fuzzTarget{pkg: fuzzFixturePackage, name: "FuzzPresent"}) {
		t.Fatalf("compiler manifest lost declared target: %v, %v", compiled, err)
	}
	if _, err = discoverFuzzTargets(t.Context(), dir, []string{fuzzFixturePackage}, nil); err == nil || !strings.Contains(err.Error(), "omitted compiler target") {
		t.Fatalf("suppressed target was not detected: %v", err)
	}
	// The omitted target is independently runnable; the fixture only suppresses listing.
	if err = runFuzzTarget(t.Context(), dir, fuzzTarget{pkg: fuzzFixturePackage, name: "FuzzPresent"}, "1x", nil); err != nil {
		t.Fatal(err)
	}
}

func TestCompilerFuzzManifestIncludesExternalAliasedTests(t *testing.T) {
	t.Parallel()
	dir := fuzzLifecycleFixture(t)
	source := `package fixture_test
import("os";qa "testing")
func FuzzExternal(f *qa.F) {f.Add(1);f.Fuzz(func(t *qa.T,n int){if err:=os.WriteFile("external.executed",[]byte("external"),0600);err!=nil{t.Fatal(err)}})}
`
	if err := os.WriteFile(filepath.Join(dir, "external_test.go"), []byte(source), fileMode); err != nil {
		t.Fatal(err)
	}
	targets, err := discoverFuzzTargets(t.Context(), dir, []string{fuzzFixturePackage}, nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(targets) != 3 {
		t.Fatalf("external test changed target inventory: %v", targets)
	}
	target := fuzzTarget{pkg: fuzzFixturePackage, name: "FuzzExternal"}
	if !slices.Contains(targets, target) {
		t.Fatalf("external fuzz target missing: %v", targets)
	}
	if err = runFuzzTarget(t.Context(), dir, target, "1x", nil); err != nil {
		t.Fatal(err)
	}
	data, err := readInRoot(dir, "external.executed")
	if err != nil || string(data) != "external" {
		t.Fatalf("external fuzz callback did not execute: %q, %v", data, err)
	}
}

func TestCompilerFuzzTableUsesTypedDeclarationAndAllowsEmptyTable(t *testing.T) {
	t.Parallel()
	source := `package main
import qa "testing"
var fixture = "var fuzzTargets = []testing.InternalFuzzTarget{{\"FuzzBogus\", fake.FuzzBogus}}"
var unrelated = []qa.InternalFuzzTarget{{"FuzzUnrelated", fake.FuzzUnrelated}}
var fuzzTargets = []qa.InternalFuzzTarget{{"FuzzInternal", internal.FuzzInternal},{"FuzzExternal", external.FuzzExternal}}
`
	targets, err := compilerFuzzTargets(fuzzFixturePackage, []byte(source))
	want := []fuzzTarget{{pkg: fuzzFixturePackage, name: "FuzzInternal"}, {pkg: fuzzFixturePackage, name: "FuzzExternal"}}
	if err != nil || !slices.Equal(targets, want) {
		t.Fatalf("generated typed table: %v, %v", targets, err)
	}
	empty := `package main;import "testing";var fuzzTargets=[]testing.InternalFuzzTarget{}`
	if targets, err = compilerFuzzTargets(fuzzFixturePackage, []byte(empty)); err != nil || len(targets) != 0 {
		t.Fatalf("valid empty compiler table: %v, %v", targets, err)
	}
	for _, invalid := range []string{
		`package main;import "testing";var unrelated=[]testing.InternalFuzzTarget{}`,
		`package main;import "testing";var fuzzTargets=[]testing.InternalTest{}`,
		`package main;import qa "other";var fuzzTargets=[]qa.InternalFuzzTarget{}`,
		`package main;import "testing";var fuzzTargets=[]testing.InternalFuzzTarget{{"FuzzA",fake.FuzzB}}`,
		`package main;import "testing";var fuzzTargets=[]testing.InternalFuzzTarget{{"FuzzA",fake.FuzzA},{"FuzzA",other.FuzzA}}`,
	} {
		if targets, err = compilerFuzzTargets(fuzzFixturePackage, []byte(invalid)); err == nil {
			t.Fatalf("invalid generated table accepted: %v", targets)
		}
	}
}

func TestCompilerFuzzManifestRejectsMissingGeneratedEvidence(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	generated := filepath.Join(dir, "generated-testmain.go")
	data := "// Code generated by 'go test'. DO NOT EDIT.\npackage main;import \"testing\";var fuzzTargets=[]testing.InternalFuzzTarget{}"
	if err := os.WriteFile(generated, []byte(data), fileMode); err != nil {
		t.Fatal(err)
	}
	original := discoveredPackage{ImportPath: fuzzFixturePackage, Name: "fixture", TestGoFiles: []string{"fuzz_test.go"}}
	main := discoveredPackage{ImportPath: fuzzFixturePackage + ".test", Name: "main", GoFiles: []string{generated}}
	encode := func(packages ...discoveredPackage) string {
		var output strings.Builder
		for _, pkg := range packages {
			if err := json.NewEncoder(&output).Encode(pkg); err != nil {
				t.Fatal(err)
			}
		}
		return output.String()
	}
	missingFile := main
	missingFile.GoFiles = []string{filepath.Join(dir, "missing.go")}
	symlink := filepath.Join(dir, "link.go")
	if err := os.Symlink(generated, symlink); err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{dir, symlink} {
		if _, err := readCompilerFuzzMain(path); err == nil {
			t.Fatalf("nonregular or symlink source accepted: %s", path)
		}
	}
	for _, metadata := range []string{"", `{`, encode(original), encode(original, missingFile), encode(original, original, main)} {
		if targets, err := parseCompilerFuzzManifest(t.Context(), strings.NewReader(metadata)); err == nil {
			t.Fatalf("missing compiler evidence accepted: %v", targets)
		}
	}
	if targets, err := parseCompilerFuzzManifest(t.Context(), strings.NewReader(encode(original, main))); err != nil || len(targets) != 0 {
		t.Fatalf("valid empty compiler manifest: %v, %v", targets, err)
	}
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	if _, err := compilerFuzzManifest(ctx, dir, []string{"not-a-package"}, nil); !errors.Is(err, context.Canceled) {
		t.Fatalf("compiler discovery lost cancellation: %v", err)
	}
}
